#!/bin/sh
# Regenerate Sources/HIPCore/BuiltinLibrary.swift from Sources/HIPCore/Library.
# The library is compiled into the binary so its code signature covers it;
# HIPCoreTests fails if the two drift apart.
set -eu
cd "$(dirname "$0")/../Sources/HIPCore"
out=BuiltinLibrary.swift
{
  echo '// Generated by scripts/gen-library.sh from Sources/HIPCore/Library. Do not edit.'
  echo
  echo '/// The built-in check library: relative path and contents of each file.'
  echo 'let builtinLibrary: [(path: String, text: String)] = ['
  (cd Library && find . -name '*.toml' | sed 's|^\./||' | LC_ALL=C sort) | while read -r f; do
    if grep -q '"""#' "Library/$f"; then
      echo "Library/$f contains \"\"\"#, which this generator cannot embed" >&2
      exit 1
    fi
    echo "    (\"$f\", #\"\"\""
    cat "Library/$f"
    # A multi-line literal drops the newline before its closing delimiter.
    echo
    echo '"""#),'
  done
  echo ']'
} >"$out.tmp"
mv "$out.tmp" "$out"
